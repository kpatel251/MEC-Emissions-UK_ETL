CREATE TABLE IF NOT EXISTS dejf_claim_admin.SG_email_notifications_stag (
  id                      BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  notification_type       VARCHAR(32)  NULL,
  notification_subtype    VARCHAR(64)  NULL,
  recipient               VARCHAR(320) NULL,
  notification_timestamp  DATETIME     NULL,
  message_status          VARCHAR(64)  NULL,
  message_action          VARCHAR(64)  NULL,
  diagnosticCode          TEXT         NULL,
  original_timestamp      DATETIME     NULL,
  messageId               VARCHAR(255) NULL,
  claim_id                VARCHAR(64)  NULL,
  user_id                 VARCHAR(64)  NULL,
  claim_status            VARCHAR(64)  NULL,
  reminder_type           VARCHAR(64)  NULL,
  reminder_subject        VARCHAR(500) NULL,
  message_body            LONGTEXT     NULL,
  url                     TEXT         NULL,
  opened                  TINYINT(1)   NOT NULL DEFAULT 0,
  clicked                 TINYINT(1)   NOT NULL DEFAULT 0,
  bounced                 TINYINT(1)   NOT NULL DEFAULT 0,
  complaint               TINYINT(1)   NOT NULL DEFAULT 0,
  KEY ix_recipient (recipient),
  KEY ix_messageId (messageId),
  KEY ix_claim_id  (claim_id),
  KEY ix_notification_timestamp (notification_timestamp)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
